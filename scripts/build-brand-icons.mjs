#!/usr/bin/env node
/**
 * Generates src/views/brand-icons.generated.js from the `simple-icons` package
 * (icons are CC0-1.0; the package is a devDependency only, so the app itself
 * stays dependency-free at runtime).
 *
 * Not every provider has a freely licensed official mark. Amazon/AWS and
 * Microsoft/Azure were REMOVED from Simple Icons at the trademark owners'
 * request, and FinOps Foundation, OffSec, and DevOps Institute were never in it.
 * Those providers fall back to a lettermark in their official brand colour —
 * see LETTERMARKS below and `src/views/brand.js`. To use a real logo you hold
 * rights to, drop its SVG path into src/views/brand-icons.local.js.
 *
 * Run: npm run icons
 */
import fs from 'fs';
import * as simpleIcons from 'simple-icons';

/** provider name in cert.js → simple-icons slug */
const PROVIDER_SLUGS = {
  'Google Cloud': 'googlecloud',
  'Cloud Native (CNCF)': 'cncf',
  'HashiCorp': 'hashicorp',
  'GitHub': 'github',
  'Docker': 'docker',
  'ISC2': 'isc2',
  'Databricks': 'databricks'
};

/** extra marks used for certification-specific badges and the discipline grid */
const EXTRA_SLUGS = ['kubernetes', 'terraform', 'prometheus', 'argo', 'opentelemetry', 'cilium', 'istio', 'backstage', 'linuxfoundation'];

const iconBySlug = new Map(
  Object.values(simpleIcons)
    .filter(i => i && i.slug && i.path)
    .map(i => [i.slug, i])
);

const picked = {};
const missing = [];

for (const [provider, slug] of Object.entries(PROVIDER_SLUGS)) {
  const icon = iconBySlug.get(slug);
  if (!icon) { missing.push(`${provider} (slug "${slug}")`); continue; }
  picked[slug] = { title: icon.title, hex: icon.hex, path: icon.path };
}
for (const slug of EXTRA_SLUGS) {
  const icon = iconBySlug.get(slug);
  if (!icon) { missing.push(`extra mark "${slug}"`); continue; }
  picked[slug] = { title: icon.title, hex: icon.hex, path: icon.path };
}

const out = `// GENERATED by scripts/build-brand-icons.mjs — do not edit. Run \`npm run icons\`.
// Official brand marks from Simple Icons (https://simpleicons.org), licensed CC0-1.0.
// Each entry is a 24x24 viewBox path.
export const BRAND_ICONS = ${JSON.stringify(picked, null, 2)};

/** provider name → brand mark slug */
export const PROVIDER_ICON_SLUGS = ${JSON.stringify(PROVIDER_SLUGS, null, 2)};
`;

fs.writeFileSync('src/views/brand-icons.generated.js', out);
console.log(`brand icons written: ${Object.keys(picked).length} official marks`);
if (missing.length) console.log(`  not available in simple-icons: ${missing.join(', ')}`);
console.log('  providers without a freely licensed mark fall back to a lettermark (see src/views/brand.js)');
