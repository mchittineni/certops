#!/usr/bin/env node
/**
 * Generates the three committed index files from the filesystem.
 *
 *   src/data/certs/<certId>/cert.js          →  catalog.generated.js   (blueprints, eagerly loaded)
 *   src/data/certs/<certId>/questions/*.js   →  registry.generated.js  (literal import() per pack)
 *   src/data/certs/<certId>/flashcards/*.js  →  manifest.generated.js  (counts only)
 *
 * The filesystem is the source of truth. Dropping a pack file into a
 * certification folder and re-running this is the entire "register content"
 * step — which is what keeps 30 certifications and ~150 packs maintainable.
 *
 * Run: npm run build:content
 */
import fs from 'fs';
import path from 'path';

const CERTS_DIR = 'src/data/certs';
const DATA_DIR = 'src/data';
const DIFFICULTIES = ['easy', 'medium', 'hard'];

const banner = name => `// GENERATED by scripts/build-content-index.mjs — do not edit.
// Run \`npm run build:content\` after adding, removing, or renaming content.
`;

function listPacks(certId, kind) {
  const dir = path.join(CERTS_DIR, certId, kind);
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir)
    .filter(f => f.endsWith('.js'))
    .sort((a, b) => a.localeCompare(b, 'en', { numeric: true }));
}

const certIds = fs.readdirSync(CERTS_DIR)
  .filter(d => fs.statSync(path.join(CERTS_DIR, d)).isDirectory())
  .filter(d => fs.existsSync(path.join(CERTS_DIR, d, 'cert.js')))
  .sort();

if (!certIds.length) {
  console.error(`No certifications found in ${CERTS_DIR}. Scaffold one with: npm run new:cert`);
  process.exit(1);
}

/* ---------------------------------------------------------------- catalog */

const blueprints = [];
for (const id of certIds) {
  const mod = await import(new URL(`../${CERTS_DIR}/${id}/cert.js`, import.meta.url).href);
  const cert = mod.default;
  if (!cert) throw new Error(`${CERTS_DIR}/${id}/cert.js has no default export`);
  if (cert.id !== id) throw new Error(`${CERTS_DIR}/${id}/cert.js declares id "${cert.id}" — it must match its folder name`);
  blueprints.push(cert);
}

const TIER_ORDER = { foundational: 0, associate: 1, professional: 2, specialty: 3 };
const CATEGORY_ORDER = [
  'Cloud Engineering',
  'DevOps & SRE',
  'Kubernetes & Cloud Native',
  'Platform Engineering',
  'FinOps',
  'DevSecOps & Security'
];
const catIndex = c => {
  const i = CATEGORY_ORDER.indexOf(c);
  return i === -1 ? CATEGORY_ORDER.length : i;
};
blueprints.sort((a, b) =>
  catIndex(a.category) - catIndex(b.category) ||
  a.provider.localeCompare(b.provider) ||
  (TIER_ORDER[a.tier] ?? 9) - (TIER_ORDER[b.tier] ?? 9) ||
  a.code.localeCompare(b.code)
);

const catalogImports = blueprints.map(c => `import ${varName(c.id)} from './certs/${c.id}/cert.js';`).join('\n');
fs.writeFileSync(path.join(DATA_DIR, 'catalog.generated.js'), `${banner()}${catalogImports}

/** Every certification blueprint. Small and eagerly loaded — questions are not. */
export const CERTIFICATIONS = [
${blueprints.map(c => `  ${varName(c.id)}`).join(',\n')}
];

export const LIVE_CERTIFICATIONS = CERTIFICATIONS.filter(c => c.status !== 'planned');

export const CATEGORIES = ${JSON.stringify(CATEGORY_ORDER.filter(c => blueprints.some(b => b.category === c)), null, 2)};

export const PROVIDERS = ${JSON.stringify([...new Set(blueprints.map(c => c.provider))], null, 2)};

export const TIERS = ${JSON.stringify([...new Set(blueprints.map(c => c.tier))].sort((a, b) => (TIER_ORDER[a] ?? 9) - (TIER_ORDER[b] ?? 9)), null, 2)};

export function getCertById(certId) {
  return CERTIFICATIONS.find(c => c.id === certId);
}
`);

function varName(id) {
  return 'CERT_' + id.toUpperCase().replace(/[^A-Z0-9]/g, '_');
}

/* ------------------------------------------------------- pack contents ---- */

/**
 * Packs are read once here and reused for the registry and the manifest.
 * Empty packs are deliberately left OUT of the registry: a scaffolded
 * certification has empty packs, and registering them would emit ~2 useless
 * bundle chunks per planned certification (94 of them at 47 planned).
 */
const packItems = new Map();   // `${certId}/${kind}/${file}` → items[]
const nonEmpty = { questions: new Map(), flashcards: new Map() };

for (const id of certIds) {
  for (const kind of ['questions', 'flashcards']) {
    const kept = [];
    for (const file of listPacks(id, kind)) {
      const mod = await import(new URL(`../${CERTS_DIR}/${id}/${kind}/${file}`, import.meta.url).href);
      if (!Array.isArray(mod.default)) throw new Error(`${CERTS_DIR}/${id}/${kind}/${file} must default-export an array`);
      packItems.set(`${id}/${kind}/${file}`, mod.default);
      if (mod.default.length) kept.push(file);
    }
    nonEmpty[kind].set(id, kept);
  }
}

/* --------------------------------------------------------------- registry */

const registryEntries = certIds.map(id => {
  const q = nonEmpty.questions.get(id);
  const f = nonEmpty.flashcards.get(id);
  const line = (kind, file) => `pack('./certs/${id}/${kind}/${file}', () => import('./certs/${id}/${kind}/${file}'))`;
  return `  '${id}': {
    questions: [${q.length ? '\n      ' + q.map(f2 => line('questions', f2)).join(',\n      ') + '\n    ' : ''}],
    flashcards: [${f.length ? '\n      ' + f.map(f2 => line('flashcards', f2)).join(',\n      ') + '\n    ' : ''}]
  }`;
}).join(',\n');

fs.writeFileSync(path.join(DATA_DIR, 'registry.generated.js'), `${banner()}/**
 * Import specifiers are literal on purpose: that is what lets a bundler emit one
 * lazily-fetched chunk per pack. A dynamic import(variable) would break the
 * production build silently.
 */
const pack = (path, load) => ({ path, load });

export const CONTENT_REGISTRY = {
${registryEntries}
};

export const DIFFICULTIES = ${JSON.stringify(DIFFICULTIES)};
`);

/* --------------------------------------------------------------- manifest */

const manifest = {};
let totalQuestions = 0;
let totalFlashcards = 0;

for (const id of certIds) {
  const count = kind => {
    const files = listPacks(id, kind);
    const items = files.flatMap(f => packItems.get(`${id}/${kind}/${f}`) || []);
    const byDifficulty = { easy: 0, medium: 0, hard: 0 };
    const byDomain = {};
    for (const it of items) {
      if (byDifficulty[it.difficulty] !== undefined) byDifficulty[it.difficulty]++;
      byDomain[it.domainId] = (byDomain[it.domainId] || 0) + 1;
    }
    return { total: items.length, byDifficulty, byDomain, packs: files.length, loadedPacks: nonEmpty[kind].get(id).length };
  };
  manifest[id] = { questions: count('questions'), flashcards: count('flashcards') };
  totalQuestions += manifest[id].questions.total;
  totalFlashcards += manifest[id].flashcards.total;
}

fs.writeFileSync(path.join(DATA_DIR, 'manifest.generated.js'), `${banner()}export const CONTENT_MANIFEST = ${JSON.stringify(manifest, null, 2)};

export const CONTENT_TOTALS = ${JSON.stringify({ questions: totalQuestions, flashcards: totalFlashcards, certifications: certIds.length }, null, 2)};
`);

console.log(`content index built: ${certIds.length} certifications · ${totalQuestions} questions · ${totalFlashcards} flashcards`);
console.log(`  catalog.generated.js  ${blueprints.length} blueprints`);
const registeredPacks = certIds.reduce((s, id) => s + nonEmpty.questions.get(id).length + nonEmpty.flashcards.get(id).length, 0);
const emptyPacks = certIds.reduce((s, id) => s + listPacks(id, 'questions').length + listPacks(id, 'flashcards').length, 0) - registeredPacks;
console.log(`  registry.generated.js ${registeredPacks} packs${emptyPacks ? ` (${emptyPacks} empty pack file(s) skipped)` : ''}`);
const live = blueprints.filter(c => c.status === 'live');
console.log(`  ${live.length} live · ${blueprints.length - live.length} planned`);
for (const category of CATEGORY_ORDER) {
  const inCat = blueprints.filter(c => c.category === category);
  if (!inCat.length) continue;
  const liveInCat = inCat.filter(c => c.status === 'live').length;
  const qs = inCat.reduce((s, c) => s + (manifest[c.id]?.questions.total || 0), 0);
  console.log(`    ${category.padEnd(26)} ${String(inCat.length).padStart(2)} certs · ${liveInCat} live · ${qs} questions`);
}
